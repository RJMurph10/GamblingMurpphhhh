import pandas as pd, numpy as np
d=pd.read_parquet('hr.parquet'); d=d[d.p_open.notna()].copy()
imp=lambda o: np.where(o<0, -o/(-o+100), 100/(o+100)); pay=lambda o: np.where(o<0, 100/-o, o/100)
d['imp']=imp(d.p_open.values); d['u']=np.where(d.hr, pay(d.p_open.values), -1.0)
d['sp_ip']=d.sp_outs/3; d['sp_hr9']=np.where(d.sp_ip>0, d.sp_hr*9/d.sp_ip.replace(0,np.nan), np.nan)
d['b_hrab']=np.where(d.b_ab>0, d.b_hr/d.b_ab.replace(0,np.nan), np.nan)
ok=(d.b_ab>=100)&(d.sp_ip>=30)
def rep(lbl, sel):
    x=d[sel]
    by=x.groupby('season').agg(n=('u','size'),hit=('hr','mean'),imp=('imp','mean'),roi=('u','mean'))
    s=' | '.join(f"{i}: {int(r.n)} bets, hit {r.hit:.3f} vs {r.imp:.3f} implied, ROI {r.roi:+.3f}" for i,r in by.iterrows())
    print(f"{lbl:58s} all {len(x):6d}  ROI {x.u.mean():+.3f}  || {s}")
rep('Every HR yes bet (opener)', d.p_open.notna())
rep('Qualified sample (batter 100+ AB, SP 30+ IP)', ok)
rep('AVG >= .250 & SP ERA >= 5.00', ok&(d.avg>=.25)&(d.sp_era>=5))
rep('AVG >= .250 & SP ERA >= 4.50', ok&(d.avg>=.25)&(d.sp_era>=4.5))
rep('AVG >= .275 & SP ERA >= 5.00', ok&(d.avg>=.275)&(d.sp_era>=5))
rep('AVG >= .250 & SP ERA >= 5.50', ok&(d.avg>=.25)&(d.sp_era>=5.5))
rep('SP ERA <= 3.00 (control)', ok&(d.sp_era<=3))
rep('HR/AB >= .050 & SP HR/9 >= 1.5', ok&(d.b_hrab>=.05)&(d.sp_hr9>=1.5))
rep('HR/AB >= .060 & SP HR/9 >= 1.5', ok&(d.b_hrab>=.06)&(d.sp_hr9>=1.5))
rep('HR/AB >= .050 & SP ERA >= 5.00', ok&(d.b_hrab>=.05)&(d.sp_era>=5))
rep('HR/AB >= .050 & SP HR/9 >= 1.5 & price +300 or longer', ok&(d.b_hrab>=.05)&(d.sp_hr9>=1.5)&(d.p_open>=300))
rep('Price +250 to +400 (shortest favorites)', d.p_open.between(250,400))
rep('Price +800 or longer (long shots)', d.p_open>=800)
